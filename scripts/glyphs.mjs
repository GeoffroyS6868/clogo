// Generates app/utils/glyphs.ts: the outlines of the printable ASCII characters, ready to use as shapes.
// Run with `pnpm glyphs`. The font is a dev dependency only: nothing from it is loaded at runtime.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const FONT = fileURLToPath(new URL('../node_modules/@fontsource/inter/files/inter-latin-700-normal.woff', import.meta.url))
const OUT = fileURLToPath(new URL('../app/utils/glyphs.ts', import.meta.url))
const FIRST = 0x21
const LAST = 0x7E
// Largest side of every glyph, in the unit box [-50, 50]²
const SIDE = 100
// Samples per curve when measuring the radius
const STEPS = 16

const bytes = readFileSync(FONT)
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))

const num = v => String(Number(v.toFixed(2)) + 0)

// A TypeScript key between quotes, the way the linter wants it
function quote(key) {
  if (key === '\'' || key === '\\') return `'\\${key}'`
  return `'${key}'`
}

// Points along a command, from the previous point, to measure the farthest distance from the origin
function* samples(cmd, from) {
  if (cmd.type === 'Q') {
    for (let i = 1; i <= STEPS; i++) {
      const t = i / STEPS
      const u = 1 - t
      yield [u * u * from[0] + 2 * u * t * cmd.x1 + t * t * cmd.x, u * u * from[1] + 2 * u * t * cmd.y1 + t * t * cmd.y]
    }
  } else if (cmd.type === 'C') {
    for (let i = 1; i <= STEPS; i++) {
      const t = i / STEPS
      const u = 1 - t
      yield [
        u ** 3 * from[0] + 3 * u * u * t * cmd.x1 + 3 * u * t * t * cmd.x2 + t ** 3 * cmd.x,
        u ** 3 * from[1] + 3 * u * u * t * cmd.y1 + 3 * u * t * t * cmd.y2 + t ** 3 * cmd.y
      ]
    }
  } else if (cmd.type === 'M' || cmd.type === 'L') {
    yield [cmd.x, cmd.y]
  }
}

function outline(char) {
  const glyph = font.charToGlyph(char)
  if (!glyph.index) return null
  // y already points down, like SVG
  const path = glyph.getPath(0, 0, font.unitsPerEm)
  const box = path.getBoundingBox()
  const scale = SIDE / Math.max(box.x2 - box.x1, box.y2 - box.y1)
  const cx = (box.x1 + box.x2) / 2
  const cy = (box.y1 + box.y2) / 2
  const fx = x => (x - cx) * scale
  const fy = y => (y - cy) * scale
  let radius = 0
  let at = [0, 0]
  const parts = []
  let open = false
  let last = ''
  for (const cmd of path.commands) {
    const m = { ...cmd }
    for (const k of ['x', 'x1', 'x2']) if (k in m) m[k] = fx(m[k])
    for (const k of ['y', 'y1', 'y2']) if (k in m) m[k] = fy(m[k])
    for (const [x, y] of samples(m, at)) radius = Math.max(radius, Math.hypot(x, y))
    if (m.type === 'Z') {
      if (open) parts.push('Z')
      open = false
      continue
    }
    // The font leaves contours open (the fill closes them): close each one, for the outline paint
    if (m.type === 'M' && open) parts.push('Z')
    const end = `${num(m.x)} ${num(m.y)}`
    // Skip a line that goes nowhere
    if (m.type === 'L' && end === last) continue
    if (m.type === 'M' || m.type === 'L') parts.push(`${m.type}${end}`)
    else if (m.type === 'Q') parts.push(`Q${num(m.x1)} ${num(m.y1)} ${end}`)
    else parts.push(`C${num(m.x1)} ${num(m.y1)} ${num(m.x2)} ${num(m.y2)} ${end}`)
    open = true
    last = end
    at = [m.x, m.y]
  }
  if (open) parts.push('Z')
  // Rounded up, so that the bounding circle never cuts the glyph
  return { d: parts.join(''), radius: Math.ceil(radius * 100) / 100 }
}

const rows = []
for (let code = FIRST; code <= LAST; code++) {
  const char = String.fromCharCode(code)
  const g = outline(char)
  if (g) rows.push(`  ${quote(char)}: { d: '${g.d}', radius: ${g.radius} }`)
  else console.warn(`No glyph for ${char}`)
}

const name = font.names.fullName?.en ?? 'Inter Bold'
const header = `// Generated by scripts/glyphs.mjs (pnpm glyphs): do not edit.
// Outlines of the printable ASCII characters from ${name}
// (${font.names.copyright?.en ?? 'The Inter Project Authors'}),
// licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).
// Each path is centred on its bounding box and scaled so that its largest side is ${SIDE}.
`

writeFileSync(OUT, `${header}
export const GLYPHS: Record<string, { d: string, radius: number }> = {
${rows.join(',\n')}
}
`)
console.log(`${rows.length} glyphs, ${name}`)
